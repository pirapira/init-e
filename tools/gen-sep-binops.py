#!/usr/bin/env python3
"""Generate GuestBound/SepBinops.lean (instances of `binop_framed`) and
GuestBound/SepPushWords.lean (instances of `pushLoad_framed`) for the handlers
whose body has the matching shape. Run from the repository root."""
import re

SRC = open('Guest/SoftwareAst.lean').read()

def names():
    """(index in guestAst, function name) for every function declaration."""
    tail = SRC[SRC.rindex('def guestAst'):]
    items = re.findall(r'guest[A-Z][a-z]+_\w+', tail)
    return [(i, it[len('guestFn_'):]) for i, it in enumerate(items) if it.startswith('guestFn_')]

def body(name):
    i = SRC.index('{ name := "%s"' % name)
    k = SRC.index('(', SRC.index('body :=', i))
    d = 0
    for q in range(k, len(SRC)):
        if SRC[q] == '(':
            d += 1
        elif SRC[q] == ')':
            d -= 1
            if d == 0:
                return re.sub(r'\s+', ' ', SRC[k:q + 1])

PAT = re.compile(
    r'^\(Prog\.decCall "x" \(Shape\.comb \[Shape\.one, Shape\.one, Shape\.one, Shape\.one\]\) "stack_pop" \[\] '
    r'\(Prog\.decCall "y" \(Shape\.comb \[Shape\.one, Shape\.one, Shape\.one, Shape\.one\]\) "stack_pop" \[\] '
    r'\(Prog\.seq \(Prog\.call \(some \(none, none\)\) "charge_gas" \[\(Exp\.const \(BitVec\.ofNat 64 (\d+)\)\)\]\) '
    r'\(Prog\.decCall "r" \(Shape\.comb \[Shape\.one, Shape\.one, Shape\.one, Shape\.one\]\) "(\w+)" '
    r'\[\(Exp\.var VarKind\.local "x"\), \(Exp\.var VarKind\.local "y"\)\] '
    r'\(Prog\.seq \(Prog\.call \(some \(none, none\)\) "stack_push" \[\(Exp\.var VarKind\.local "r"\)\]\) '
    r'\(Prog\.seq \(Prog\.call \(some \(none, none\)\) "pc_add" \[\(Exp\.const \(BitVec\.ofNat 64 1\)\)\]\) '
    r'\(Prog\.return \(Exp\.const \(BitVec\.ofNat 64 0\)\)\)\)\)\)\)\)\)$')

DEPTH = 6

ALL = dict((n, body(n)) for _, n in names())


def pure(f, seen=None):
    """f and its callees have no store, global assignment, host call or raise."""
    seen = seen or set()
    if f in seen:
        return True
    seen.add(f)
    b = ALL[f]
    if re.search(r'Prog\.store|Prog\.assign VarKind\.global|shMem|extCall|Prog\.raise|some \("', b):
        return False
    return all(pure(c, seen) for c in set(re.findall(r'"(\w+)"', b)) if c in ALL and c != f)


out = ['''import InitECandidate.Solver.GuestBound.SepBinop

/-!
# The binary stack handlers

Generated by `tools/gen-sep-binops.py`. Each handler whose body is
`binopBody f G` gets its framed specification from `binop_framed`; the callee
is checked to change nothing (`keepFn quietLeaf`) and never to raise
(`raiseFn`).
-/

namespace InitECandidate.Solver.GuestBound
open Flapjack

variable {σ : Type} {E : Env σ}
''']
ns = names()
for i, n in ns:
    m = PAT.match(body(n))
    if not m:
        continue
    gas, f = m.group(1), m.group(2)
    if not pure(f):
        print('skipped', n, '(callee', f, 'is not pure)')
        continue
    out.append(f'''
theorem «{n}_framed» (hE : GuestEnv E) (parameters : List VarName) (body : Prog Word)
    (hlookup : lookupPanFunction "{n}" E.functions = some (parameters, body))
    (s : St σ) (e sp cap base pv fv gl used pc : Word) (ok : StackOk sp cap base pv fv) :
    WPFt E s body (OpW e sp cap base pv fv gl used pc)
      (BinopPost s.ffi e sp cap base pv fv gl used pc {gas}#64) := by
  have hbody := (fun_of_index {i} hE.functions (by guest_decl_at {i}) (by decide +kernel)
    hlookup).1
  subst hbody
  exact binop_framed hE {gas}#64
    (keepFn_sound (quietKeeper E) hE.functions {DEPTH} "{f}"
      (show keepFn quietLeaf Guest.Software.guestAst {DEPTH} "{f}" = true by decide +kernel))
    (raiseFn_sound _ hE.functions {DEPTH} "{f}"
      (show raiseFn (fun _ => false) Guest.Software.guestAst {DEPTH} "{f}" = true by
        decide +kernel))
    s e sp cap base pv fv gl used pc ok
''')
out.append('\nend InitECandidate.Solver.GuestBound\n')
open('submission/InitECandidate/Solver/GuestBound/SepBinops.lean', 'w').write(''.join(out))
print(len(out) - 2, 'handlers')

# Handlers of the shape charge_gas(G); stack_push_word(lds 1 a); pc_add(1); return 0.
PAT2 = re.compile(
    r'^\(Prog\.seq \(Prog\.call \(some \(none, none\)\) "charge_gas" \[\(Exp\.const \(BitVec\.ofNat 64 (\d+)\)\)\]\) '
    r'\(Prog\.seq \(Prog\.call \(some \(none, none\)\) "stack_push_word" \[\(Exp\.load Shape\.one (.*)\)\]\) '
    r'\(Prog\.seq \(Prog\.call \(some \(none, none\)\) "pc_add" \[\(Exp\.const \(BitVec\.ofNat 64 1\)\)\]\) '
    r'\(Prog\.return \(Exp\.const \(BitVec\.ofNat 64 0\)\)\)\)\)\)$')

out = ['''import InitECandidate.Solver.GuestBound.SepPushWord

/-!
# The handlers that push one loaded word

Generated by `tools/gen-sep-binops.py` from `pushLoad_framed`.
-/

namespace InitECandidate.Solver.GuestBound
open Flapjack

variable {σ : Type} {E : Env σ}
''']
for i, n in ns:
    m = PAT2.match(body(n))
    if not m:
        continue
    gas, a = m.group(1), m.group(2)
    out.append(f'''
theorem «{n}_framed» (hE : GuestEnv E) (parameters : List VarName) (body : Prog Word)
    (hlookup : lookupPanFunction "{n}" E.functions = some (parameters, body))
    (s : St σ) (e sp cap base pv fv gl used pc : Word) (ok : StackOk sp cap base pv fv) :
    WPFt E s body (OpW e sp cap base pv fv gl used pc)
      (PushPost s.ffi e sp cap base pv fv gl used pc {gas}#64) := by
  have hbody := (fun_of_index {i} hE.functions (by guest_decl_at {i}) (by decide +kernel)
    hlookup).1
  subst hbody
  exact pushLoad_framed hE {gas}#64
    {a}
    s e sp cap base pv fv gl used pc ok
''')
out.append('\nend InitECandidate.Solver.GuestBound\n')
open('submission/InitECandidate/Solver/GuestBound/SepPushWords.lean', 'w').write(''.join(out))
print(len(out) - 2, 'push-word handlers')
