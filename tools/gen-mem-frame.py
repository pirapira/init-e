#!/usr/bin/env python3
"""Generate GuestBound/MemFrame.lean: memcpy and memzero change memory only
inside the destination block (any alignment, any source).

Run from the repository root: python3 tools/gen-mem-frame.py
"""
OUT = 'submission/InitECandidate/Solver/GuestBound/MemFrame.lean'

HEAD = r'''import InitECandidate.Solver.GuestBound.KeyNibbles
import InitECandidate.Solver.GuestBound.MemZeroFrame

/-!
# `memcpy` and `memzero` write only the destination block

Generated by `tools/gen-mem-frame.py`.

For any destination, source and length (no alignment or disjointness
assumed): the call returns 0, keeps globals and the FFI state, and leaves
every memory cell outside `[dst / 8 * 8, dst + n)` unchanged. The four loops
of each function share one invariant, `FrI`.
-/

namespace InitECandidate.Solver.GuestBound
open Flapjack

variable {σ : Type} {E : Env σ} {s : St σ} {Q : Result σ → Prop}

/-- Memory `m` agrees with `m0` outside the cells of `[dst, dst + n)`. -/
def Hull (m0 : Word → Option (PanValue Word)) (dst nW : Word)
    (m : Word → Option (PanValue Word)) : Prop :=
  ∀ x : Word, (x.toNat < dst.toNat / 8 * 8 ∨ dst.toNat + nW.toNat ≤ x.toNat) → m x = m0 x

/-- The invariant of the loops: `i = j ≤ n` and only the block has changed. -/
def FrI (g : VarName → Option (PanValue Word)) (m0 : Word → Option (PanValue Word))
    (f : FfiState σ) (dst nW : Word) (a : St σ) : Prop :=
  a.globals = g ∧ a.ffi = f ∧ a.locals "dst" = some (.word dst) ∧
    a.locals "n" = some (.word nW) ∧ Hull m0 dst nW a.memory ∧
    ∃ j : Nat, a.locals "i" = some (.word (BitVec.ofNat 64 j)) ∧ j ≤ nW.toNat

/-- A word store inside the block. -/
theorem WPs.seq_store_hull (hE : GuestEnv E) {a val rest : _} {addr dst nW : Word}
    {m0 : Word → Option (PanValue Word)}
    (ha : ∀ y, E.eval s a = some y → y = .word addr)
    (hv : ∀ y, E.eval s val = some y → ∃ w : Word, y = .word w)
    (hlo : dst.toNat ≤ addr.toNat) (hhi : addr.toNat < dst.toNat + nW.toNat)
    (hfr : Hull m0 dst nW s.memory)
    (h : ∀ m, Hull m0 dst nW m → WPs E ⟨s.locals, s.globals, m, s.ffi⟩ rest Q) :
    WPs E s (.seq (.store a val) rest) Q := by
  intro r hr
  obtain ⟨r1, h1, hrest⟩ := runs_seq.mp hr
  obtain ⟨fuel, n, hrun⟩ := h1
  rcases store_word_inv hE.mem hrun with herr | ⟨addr', y, m, ha', hy, rfl, hm⟩
  · cases r1 with
    | error l g m f => simp only at hrest; subst hrest; exact Or.inl trivial
    | _ => cases herr
  have := ha _ ha'
  simp only [PanValue.word.injEq] at this
  subst this
  obtain ⟨w, rfl⟩ := hv _ hy
  have hm' := hm w rfl
  subst hm'
  refine h _ (fun x hx => ?_) r hrest
  rw [setCell_ne _ (by intro hh; have := congrArg BitVec.toNat hh; omega)]
  exact hfr x hx

/-- A byte store inside the block. -/
theorem WPs.seq_storeByte_hull (hE : GuestEnv E) {a val rest : _} {addr dst nW : Word}
    {m0 : Word → Option (PanValue Word)}
    (ha : ∀ y, E.eval s a = some y → y = .word addr)
    (hlo : dst.toNat ≤ addr.toNat) (hhi : addr.toNat < dst.toNat + nW.toNat)
    (hfr : Hull m0 dst nW s.memory)
    (h : ∀ m, Hull m0 dst nW m → WPs E ⟨s.locals, s.globals, m, s.ffi⟩ rest Q) :
    WPs E s (.seq (.storeByte a val) rest) Q := by
  refine WPs.seq_storeByte_fr hE ha (fun m _ hm => h m (fun x hx => ?_))
  rw [hm x (by omega)]
  exact hfr x hx

theorem addr_toNat (dst : Word) (j : Nat) (c : Word) (h : dst.toNat + j + c.toNat < 2 ^ 64) :
    (dst + BitVec.ofNat 64 j + c).toNat = dst.toNat + j + c.toNat := by
  rw [BitVec.toNat_add, BitVec.toNat_add, BitVec.toNat_ofNat]
  omega

theorem addr0_toNat (dst : Word) (j : Nat) (h : dst.toNat + j < 2 ^ 64) :
    (dst + BitVec.ofNat 64 j).toNat = dst.toNat + j := by
  rw [BitVec.toNat_add, BitVec.toNat_ofNat]
  omega

theorem idx_add (j : Nat) (k : Nat) :
    (BitVec.ofNat 64 j : Word) + BitVec.ofNat 64 k = BitVec.ofNat 64 (j + k) := by
  apply BitVec.eq_of_toNat_eq
  simp only [BitVec.toNat_add, BitVec.toNat_ofNat]
  omega

/-- A load of one word, if it succeeds, gives a word. -/
theorem load_one_word (hE : GuestEnv E) (a : Exp Word) :
    ∀ y, E.eval s (.load .one a) = some y → ∃ w : Word, y = .word w := by
  intro y hy
  obtain ⟨addr, w, -, rfl, -⟩ := eval_load_one hE.mem hy
  exact ⟨w, rfl⟩

theorem const_word (c : Word) :
    ∀ y, E.eval s (.const c) = some y → ∃ w : Word, y = .word w := by
  intro y hy
  rw [eval_const] at hy
  exact ⟨c, (Option.some.inj hy).symm⟩

/-- The guard `n >= i + k` came out true. -/
theorem guard_ge (hE : GuestEnv E) {a : St σ} {nW : Word} {j : Nat} (k : Word)
    (hN : a.locals "n" = some (.word nW)) (hI : a.locals "i" = some (.word (BitVec.ofNat 64 j)))
    (hj : j ≤ nW.toNat) (h64 : nW.toNat + k.toNat < 2 ^ 64)
    (hct : CondTrue E a (.cmp .notLower (.var .local "n")
      (.op .add [.var .local "i", .const k]))) : j + k.toNat ≤ nW.toNat := by
  obtain ⟨w, cc, hcond, hw⟩ := hct
  have hc := eval_cmp_inv hE (op := .notLower) (of_eval (w := nW) (by lk [hN]))
    (of_eval (w := BitVec.ofNat 64 j + k) (by ev [hI])) _ (cond_of_eval hcond)
  simp only [PanValue.word.injEq] at hc
  by_contra hgt
  have hl : nW < (BitVec.ofNat 64 j + k : Word) := by
    rw [BitVec.lt_def, BitVec.toNat_add, BitVec.toNat_ofNat]
    omega
  rw [hc] at hw
  simp [evalPanCmp, hl] at hw

/-- The guard `i < n` came out true. -/
theorem guard_lt (hE : GuestEnv E) {a : St σ} {nW : Word} {j : Nat}
    (hN : a.locals "n" = some (.word nW)) (hI : a.locals "i" = some (.word (BitVec.ofNat 64 j)))
    (hj : j ≤ nW.toNat)
    (hct : CondTrue E a (.cmp .lower (.var .local "i") (.var .local "n"))) : j + 1 ≤ nW.toNat := by
  obtain ⟨w, cc, hcond, hw⟩ := hct
  have hc := eval_cmp_inv hE (op := .lower) (of_eval (w := BitVec.ofNat 64 j) (by lk [hI]))
    (of_eval (w := nW) (by lk [hN])) _ (cond_of_eval hcond)
  simp only [PanValue.word.injEq] at hc
  by_contra hgt
  have hN64 := nW.isLt
  have hl : ¬ (BitVec.ofNat 64 j : Word) < nW := by
    rw [BitVec.lt_def, BitVec.toNat_ofNat]
    omega
  rw [hc] at hw
  simp [evalPanCmp, hl] at hw

'''

def loop(name, kind, K, offs, guard):
    """kind: 'store' or 'storeByte'; offs: list of offsets; K: step."""
    n = len(offs)
    vs = ' '.join(f'v{i}' for i in range(n))
    def addr(c):
        if c == 0:
            return '(.op .add [.var .local "dst", .var .local "i"])'
        return f'(.op .add [.var .local "dst", .var .local "i", .const {c}#64])'
    body = ''
    for i, c in enumerate(offs):
        body += f'(.seq (.{kind} {addr(c)} v{i}) '
    body += f'(.assign .local "i" (.op .add [.var .local "i", .const {K}#64]))' + ')' * n
    hv = ''
    if kind == 'store':
        hv = ''.join(f'\n    (hv{i} : ∀ (a : St σ) y, E.eval a v{i} = some y → ∃ w : Word, y = .word w)'
                     for i in range(n))
    width = 8 if kind == 'store' else 1
    out = f'''set_option maxHeartbeats 4000000 in
theorem {name} (hE : GuestEnv E) {{{vs} : Exp Word}}{hv}
    {{g : VarName → Option (PanValue Word)}} {{m0 : Word → Option (PanValue Word)}}
    {{f : FfiState σ}} {{dst nW : Word}} (h64 : dst.toNat + nW.toNat + 32 < 2 ^ 64)
    (hI : FrI g m0 f dst nW s) :
    WPs E s (.while {guard} {body})
      (fun r1 => match r1 with
        | .normal l g' m f' => FrI g m0 f dst nW ⟨l, g', m, f'⟩
        | r1 => Q r1) := by
  refine WPs.loopG (I := fun a => FrI g m0 f dst nW a) hI ?_ (fun a k hI _ => hI)
  rintro ⟨la, ga, ma, fa⟩ ⟨hg, hf, hD, hN, hfr, j, hIi, hjn⟩ hct
  simp only at hg hf hD hN hIi hfr
  subst hg hf
'''
    if 'notLower' in guard:
        out += f'''  have hjK : j + {K} ≤ nW.toNat :=
    guard_ge hE {K}#64 hN hIi hjn (by simp; omega) hct
'''
    else:
        out += '''  have hjK : j + 1 ≤ nW.toNat := guard_lt hE hN hIi hjn hct
'''
    for i, c in enumerate(offs):
        rule = 'WPs.seq_store_hull' if kind == 'store' else 'WPs.seq_storeByte_hull'
        hvarg = f' (hv{i} _)' if kind == 'store' else ''
        if c == 0:
            out += f'''  have a{i} := addr0_toNat dst j (by omega)
  refine {rule} hE (addr := dst + BitVec.ofNat 64 j) (dst := dst) (nW := nW)
    (of_eval (by ev [hD, hIi])){hvarg} (by omega) (by omega) hfr (fun m{i} hfr => ?_)
'''
        else:
            out += f'''  have a{i} := addr_toNat dst j {c}#64 (by simp; omega)
  simp only [show (({c}#64 : Word)).toNat = {c} from rfl] at a{i}
  refine {rule} hE (addr := dst + BitVec.ofNat 64 j + {c}#64) (dst := dst) (nW := nW)
    (of_eval (by ev [hD, hIi, BitVec.add_assoc])){hvarg} (by omega) (by omega) hfr
    (fun m{i} hfr => ?_)
'''
    out += f'''  refine WPs.assign (old := BitVec.ofNat 64 j) (by lk [hIi])
    (of_eval (w := BitVec.ofNat 64 (j + {K})) (by ev [hIi, idx_add j {K}])) ?_
  exact ⟨rfl, rfl, by lk [hD], by lk [hN], hfr, j + {K}, by lk [], hjK⟩

'''
    return out

G32 = '(.cmp .notLower (.var .local "n") (.op .add [.var .local "i", .const 32#64]))'
G8 = '(.cmp .notLower (.var .local "n") (.op .add [.var .local "i", .const 8#64]))'
G1 = '(.cmp .lower (.var .local "i") (.var .local "n"))'

text = HEAD
text += loop('loop_w32', 'store', 32, [0, 8, 16, 24], G32)
text += loop('loop_w8', 'store', 8, [0], G8)
text += loop('loop_b8', 'storeByte', 8, list(range(8)), G8)
text += loop('loop_b1', 'storeByte', 1, [0], G1)

def fn(name, idx, has_src):
    pre = '(hs : s.locals "src" = some (.word src)) ' if False else ''
    wv32 = ' '.join(['(fun a => load_one_word hE _)'] * 4) if has_src else \
        ' '.join(['(fun a => const_word _)'] * 4)
    wv8 = '(fun a => load_one_word hE _)' if has_src else '(fun a => const_word _)'
    return f'''set_option maxHeartbeats 4000000 in
/-- `{name}`: only the cells of `[dst, dst + n)` change. -/
theorem {name}_frame (hE : GuestEnv E) (parameters : List VarName) (body : Prog Word)
    (hlookup : lookupPanFunction "{name}" E.functions = some (parameters, body))
    (s : St σ) (r : Result σ) (dst nW : Word)
    (hd : s.locals "dst" = some (.word dst)) (hn : s.locals "n" = some (.word nW))
    (h64 : dst.toNat + nW.toNat + 32 < 2 ^ 64) (h : Runs E s body r) :
    Stopped r ∨ ∃ l m', r = .returned l s.globals m' s.ffi [.word 0#64] ∧
      Hull s.memory dst nW m' := by
  have hbody := (fun_of_index {idx} hE.functions (by guest_decl_at {idx}) (by decide +kernel)
    hlookup).1
  subst hbody
  dsimp only at h
  refine (?_ : WPs E s _ (fun r => ∃ l m', r = .returned l s.globals m' s.ffi [.word 0#64] ∧
    Hull s.memory dst nW m')) r h
  refine WPs.dec (w := 0#64) (of_eval (eval_const _ _)) ?_
  refine WPs.conseq (Q' := fun r => ∃ l m', r = .returned l s.globals m' s.ffi [.word 0#64] ∧
    Hull s.memory dst nW m') ?_
    (by rintro r ⟨l, m', rfl, hrel⟩; exact ⟨_, m', rfl, hrel⟩)
  have hinit : FrI s.globals s.memory s.ffi dst nW
      ⟨updatePanValueMap s.locals "i" (.word 0#64), s.globals, s.memory, s.ffi⟩ :=
    ⟨rfl, rfl, by lk [hd], by lk [hn], fun _ _ => rfl, 0, by lk [], Nat.zero_le _⟩
  refine WPs.seqG (fun a => FrI s.globals s.memory s.ffi dst nW a) ?_ ?_
  · refine WPs.ite_both (fun w _ => ?_)
    split
    · exact WPs.skip hinit
    · refine WPs.seqG (fun a => FrI s.globals s.memory s.ffi dst nW a)
        (loop_w32 hE {wv32} h64 hinit) ?_
      intro a hIa
      exact loop_w8 hE {wv8} h64 hIa
  intro a hIa
  refine WPs.seqG (fun a => FrI s.globals s.memory s.ffi dst nW a) (loop_b8 hE h64 hIa) ?_
  intro a hIa
  refine WPs.seqG (fun a => FrI s.globals s.memory s.ffi dst nW a) (loop_b1 hE h64 hIa) ?_
  rintro a ⟨hg, hf, -, -, hfr, -⟩
  refine WPs.ret (of_eval (eval_const _ _)) ?_
  exact ⟨_, a.memory, by rw [hg, hf], hfr⟩

'''

text += fn('memzero', 17, False)
text += fn('memcpy', 16, True)
text += 'end InitECandidate.Solver.GuestBound\n'
open(OUT, 'w').write(text)
print('wrote', OUT)
