#!/usr/bin/env python3
"""Regenerate GuestBound/FnsH.lean: step bounds, from states with the heap
pointer in the heap, of the functions between bn254_pairing_check and
run_frames. Run from the repository root.

Each function body is walked from the AST text in Guest/SoftwareAst.lean. A
subprogram that reaches none of the conditionally bounded functions is left to
cost_derive; the others get the CostsH rule of their constructor."""
import re
SRC = open('Guest/SoftwareAst.lean').read()
LINES = SRC.split('\n')
START = [k for k, l in enumerate(LINES) if l.startswith('def guestAst')][0]
DECLS = re.findall(r'guest(?:Fn|Global|Exn)_[A-Za-z0-9_]+', '\n'.join(LINES[START + 1:]))
INDEX = {n[8:]: k for k, n in enumerate(DECLS) if n.startswith('guestFn_')}

# function -> literal bound; in call-graph order
FUNS = [
    ("pre_alt_bn128_pairing_check", "2" + "0" * 88),
    ("run_precompile", "1" + "0" * 179),
    ("frame_prologue", "1" + "0" * 180),
    ("frame_start", "1" + "0" * 181),
    ("start_child", "1" + "0" * 182),
    ("generic_create", "1" + "0" * 183),
    ("op_create", "1" + "0" * 184),
    ("op_create2", "1" + "0" * 184),
    ("generic_call", "1" + "0" * 183),
    ("op_call", "1" + "0" * 184),
    ("op_callcode", "1" + "0" * 184),
    ("op_delegatecall", "1" + "0" * 184),
    ("op_staticcall", "1" + "0" * 184),
]
COND = {"bn254_pairing_check"} | {f for f, _ in FUNS}

def body_text(name):
    i = SRC.index('{ name := "%s"' % name)
    k = SRC.index('(', SRC.index('body :=', i))
    return SRC[k:close(SRC, k) + 1]

def close(s, k):
    d = 0
    q = k
    while True:
        c = s[q]
        if c == '"':
            q = s.index('"', q + 1)
        elif c in '([':
            d += 1
        elif c in ')]':
            d -= 1
            if d == 0:
                return q
        q += 1

def args_of(t):
    """Top-level arguments of the application `(Head a b c)` as source slices."""
    assert t[0] == '(' and t[-1] == ')', t[:40]
    inner = t[1:-1].strip()
    out = []
    q = 0
    while q < len(inner):
        c = inner[q]
        if c.isspace():
            q += 1
        elif c in '([':
            e = close(inner, q)
            out.append(inner[q:e + 1]); q = e + 1
        elif c == '"':
            e = inner.index('"', q + 1)
            out.append(inner[q:e + 1]); q = e + 1
        else:
            e = q
            while e < len(inner) and not inner[e].isspace():
                e += 1
            out.append(inner[q:e]); q = e
    return out

def reaches(t):
    return any('"%s"' % f in t for f in COND)

def callee(f):
    f = f.strip('"')
    return f"(H.«{f}» hE)" if f in COND else f"(FunCost.toH (Fn.«{f}» hE))"

def gen(t):
    t = t.strip()
    if not reaches(t):
        return "(CostsH.of_costs (by cost_derive []))"
    a = args_of(t)
    head = a[0]
    if head == 'Prog.seq':
        return f"(CostsH.seq hE (by decide +kernel) {gen(a[1])} {gen(a[2])})"
    if head == 'Prog.ite':
        return f"(CostsH.ite _ {gen(a[2])} {gen(a[3])})"
    if head == 'Prog.dec':
        return f"(CostsH.dec _ _ _ {gen(a[4])})"
    if head == 'Prog.decCall':
        f = a[3].strip('"')
        assert f not in ('heap_mark', 'heap_release'), f
        return f"(CostsH.decCall hE _ _ _ (by decide) {callee(a[3])} {gen(a[5])})"
    if head == 'Prog.call':
        info = re.sub(r'\s+', ' ', a[1])
        assert info.startswith('(some ('), info
        if info.endswith(', none))'):
            return f"(CostsH.call _ _ {callee(a[2])})"
        # a handler: it must not reach a conditionally bounded function itself
        pair = args_of(info)[1]
        handler = pair[pair.index('(some ('):]
        assert not reaches(handler), handler[:80]
        return f"(CostsH.callH _ _ _ _ {callee(a[2])} (by cost_derive []))"
    raise Exception("unsupported: " + head)

out = '''import InitECandidate.Solver.GuestBound.Fns.L16
import InitECandidate.Solver.GuestBound.PairingCheck
import InitECandidate.Solver.GuestBound.CostsH

/-!
# Callers of `bn254_pairing_check`, bounded from `HeapOk` states

Generated by `tools/gen-fnsh.py`; do not edit. `H.«f»` is the step bound of
`f` from states whose heap pointer is in the heap, for the functions on the
call path from `run_frames` down to `bn254_pairing_check`.
-/

namespace InitECandidate.Solver.GuestBound
open Flapjack

variable {σ : Type} {E : Env σ}

namespace H

theorem «bn254_pairing_check» (hE : GuestEnv E) :
    FunCostH E "bn254_pairing_check" 1''' + '0' * 88 + ''' :=
  fun parameters body hlookup fuel s r n hP hrun hne =>
    ⟨bn254_pairing_check_cost hE parameters body hlookup fuel s r n hP.1 hrun hne, trivial⟩
'''
for f, lit in FUNS:
    i = INDEX[f]
    out += f'''
set_option maxRecDepth 100000 in
theorem «{f}» (hE : GuestEnv E) :
    FunCostH E "{f}" {lit} := by
  intro parameters body hlookup
  have hbody := (fun_of_index {i} hE.functions (by guest_decl_at {i}) (by decide +kernel)
    hlookup).1
  subst hbody
  dsimp only
  refine CostsH.mono
    {gen(body_text(f))}
    ?_
  decide +kernel
'''
out += '''
end H

end InitECandidate.Solver.GuestBound
'''
open('submission/InitECandidate/Solver/GuestBound/FnsH.lean', 'w').write(out)
