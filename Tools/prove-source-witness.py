#!/usr/bin/env python3
"""Build resumable kernel-checked execution checkpoints and close the K >= 3 proof.

No runtime scout result is accepted as a certificate. Every generated module is
checked by Lean; the final output-byte theorem and axiom audit must also pass.
"""
import argparse
import fcntl
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / 'work/score-lower-bound/kernel-batch'
FOLDER = ROOT / 'InitE/SourceWitness'
STATUS = WORK / 'status.json'
HEADER = '''-- Generated by Tools/prove-source-witness.py; Lean checks every term and equality.
import InitE.SourceWitness.Execution{previous:03d}
set_option Elab.async false
set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option cbv.maxSteps 1000000000
open scoped InitE.SourceAtomicReduction InitE.SourceSupportReduction Tools.SourceCheckpoint
  InitE.SourceContextReduction InitE.SourceLookupReduction InitE.SourceMemoryReduction
  InitE.SourceReduction InitE.NameComputation InitE.SourceWitness
namespace InitE.SourceWitness
'''


def save_status(**values):
    old = json.loads(STATUS.read_text()) if STATUS.exists() else {}
    old.update(values, updated_at=time.time())
    temporary = STATUS.with_suffix('.tmp')
    temporary.write_text(json.dumps(old, indent=2) + '\n')
    temporary.replace(STATUS)


def write_generated(path, content):
    if path.exists():
        if path.read_text() != content:
            raise RuntimeError(f'Refusing to overwrite different existing source: {path}')
        return
    path.write_text(content)


def build(module, label):
    log = WORK / f'{label}.log'
    with log.open('w') as stream:
        result = subprocess.run(['lake', 'build', module], cwd=ROOT,
            env={**os.environ, 'LAKE_ARTIFACT_CACHE': 'false'},
            stdout=stream, stderr=subprocess.STDOUT)
    if result.returncode:
        raise RuntimeError(f'Lean rejected {module}; see {log}')
    return log.read_text()


def stage(index, budget):
    text = HEADER.format(previous=index-1)
    text += f'source_checkpoint execution{index:03d} := execution{index-1:03d} budget {budget}\n'
    if index == 2:
        chain = 'execution000_eq.trans (execution001_eq.trans execution002_eq)'
    else:
        chain = f'execution{index-1:03d}_from_start.trans execution{index:03d}_eq'
    text += f'''theorem execution{index:03d}_from_start : execution input 32000 = execution{index:03d} :=
  {chain}
end InitE.SourceWitness
'''
    write_generated(FOLDER / f'Execution{index:03d}.lean', text)
    save_status(phase='checking', next_stage=index, budget=budget)
    log = build(f'InitE.SourceWitness.Execution{index:03d}', f'execution{index:03d}')
    marker = re.search(rf'Checked InitE.SourceWitness.execution{index:03d} and .*?budget left: (\d+)', log)
    if not marker:
        raise RuntimeError(f'No checkpoint-completion marker for stage {index}')
    artifact = ROOT / f'.lake/build/lib/lean/InitE/SourceWitness/Execution{index:03d}.olean'
    remaining = int(marker[1])
    if remaining == 0 and artifact.stat().st_size > 512 * 1024**2:
        raise RuntimeError(f'Checkpoint {index} passed but exceeds the 512 MiB artifact limit')
    save_status(phase='checkpoint_checked', last_checked=index, next_stage=index+1,
                budget_left=remaining, artifact_bytes=artifact.stat().st_size)
    print(f'Kernel checked stage {index}; budget left {remaining}', flush=True)
    return remaining


def finish(index):
    checkpoint = f'execution{index:03d}'
    text = f'''-- Generated completion candidate: all statements below must pass the kernel.
import InitE.SourceWitness.Execution{index:03d}
import InitE.SourceWitness.Completion
set_option Elab.async false
set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option cbv.maxSteps 1000000000
namespace InitE.SourceWitness
open Flapjack

theorem witness_terminal : {checkpoint}.1 = some (.finalFfi haltEvent) := by rfl

theorem witness_run : execution input 32000 =
    (some (.finalFfi haltEvent), {checkpoint}.2) := by
  rw [{checkpoint}_from_start]
  exact Prod.ext witness_terminal rfl

theorem witness_success : outputByte input {checkpoint}.2.ffi.ioEvents ⟨32, by decide⟩ = 1 := by
  first | decide | decide_cbv
end InitE.SourceWitness

namespace InitE
open Flapjack

theorem Certificate.score_at_least_three {{submission : Submission}} {{claimed : NatE}}
    (certificate : Certificate submission claimed) : claimed.Allows 3 :=
  SourceWitness.score_from_execution certificate 32000 _
    SourceWitness.witness_run SourceWitness.witness_success

theorem Certificate.finite_score_at_least_three {{submission : Submission}} {{k : Nat}}
    (certificate : Certificate submission (.finite k)) : 3 ≤ k :=
  certificate.score_at_least_three

theorem Certificate.submission_score_at_least_three {{submission : Submission}} {{claimed : NatE}}
    (certificate : Certificate submission claimed) : submission.K.Allows 3 := by
  rw [certificate.score]
  exact certificate.score_at_least_three
end InitE
'''
    write_generated(FOLDER / 'Final.lean', text)
    save_status(phase='checking_final', final_checkpoint=index)
    build('InitE.SourceWitness.Final', 'final')
    audit = WORK / 'Audit.lean'
    audit.write_text('import InitE.SourceWitness.Final\n'
        '#print axioms InitE.Certificate.score_at_least_three\n'
        '#print axioms InitE.Certificate.finite_score_at_least_three\n')
    result = subprocess.run(['lake', 'env', 'lean', str(audit)], cwd=ROOT,
                            text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    (WORK / 'audit.log').write_text(result.stdout)
    groups = re.findall(r'depends on axioms:\s*\[([^]]*)\]', result.stdout)
    allowed = {'propext', 'Classical.choice', 'Quot.sound'}
    if result.returncode or len(groups) != 2 or any(
        not set(filter(None, (x.strip() for x in group.split(',')))) <= allowed for group in groups):
        raise RuntimeError(f'Final axiom audit failed; see {WORK / "audit.log"}')
    root = ROOT / 'InitE.lean'
    export = 'import InitE.SourceWitness.Final\n'
    if export not in root.read_text():
        root.write_text(root.read_text() + export)
    build('InitE', 'export')
    save_status(phase='complete', final_checkpoint=index, axiom_audit='passed')
    print('Kernel proved the accepted witness and unconditional score bound K >= 3.', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--budget', type=int, default=500)
    parser.add_argument('--start', type=int)
    parser.add_argument('--stop-after', type=int, help='Optional number of new checkpoints to build')
    parser.add_argument('--max-stage', type=int, default=2000)
    args = parser.parse_args()
    if args.budget <= 0:
        parser.error('--budget must be positive')
    WORK.mkdir(parents=True, exist_ok=True)
    lock = (WORK / 'driver.lock').open('w')
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    old = json.loads(STATUS.read_text()) if STATUS.exists() else {}
    if old.get('phase') == 'complete':
        print('Proof already completed; see InitE/SourceWitness/Final.lean')
        return
    index = args.start if args.start is not None else old.get('next_stage', 2)
    if index < 2:
        parser.error('--start must be at least 2')
    try:
        save_status(phase='starting', next_stage=index, pid=os.getpid(), budget=args.budget)
        build('InitE.SourceWitness.Execution001', 'base')
        count = 0
        while index <= args.max_stage:
            if shutil.disk_usage(ROOT).free < 8 * 1024**3:
                raise RuntimeError('Less than 8 GiB disk space remains')
            remaining = stage(index, args.budget)
            if remaining > 0:
                finish(index)
                return
            index += 1
            count += 1
            if args.stop_after is not None and count >= args.stop_after:
                save_status(phase='batch_checked', next_stage=index)
                return
        raise RuntimeError('Maximum stage reached before a terminal witness was certified')
    except Exception as error:
        save_status(phase='failed', error=str(error))
        raise


if __name__ == '__main__':
    main()
